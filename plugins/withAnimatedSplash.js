/**
 * Animated launch screen (Android 12+ SplashScreen API).
 *
 * expo-splash-screen sets a static PNG as `windowSplashScreenAnimatedIcon`. This plugin
 * generates an AnimatedVectorDrawable of logo 27 ("Countdown ticks") instead: the ring lights
 * up tick by tick and the hands sweep round to the logo's 6:30 pose. A light version goes in
 * drawable/ and a dark one in drawable-night/, matching the splash backgrounds in app.json.
 *
 * List it just before "expo-splash-screen" in app.json: mods run in reverse order, so this one
 * runs after the splash plugin has written its theme and can override the icon.
 */
const { withAndroidStyles, withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const ICON = 'chronos_splash_animated';
const DURATION_MS = 1000;
const LIT_TICKS = 7; // 12 through 6, as in the logo at 6:30

const palettes = {
  light: { lit: '#8C1D30', dim: '#D8C2C2', hand: '#5F1121', minute: '#8C1D30' },
  dark: { lit: '#E8566C', dim: '#534343', hand: '#FFDADB', minute: '#FFB2B7' },
};

function tickPath(k) {
  const a = (k * Math.PI) / 6;
  const p = (r) => `${(54 + r * Math.sin(a)).toFixed(2)},${(54 - r * Math.cos(a)).toFixed(2)}`;
  return `M${p(22)} L${p(30)}`;
}

function animatedVector({ lit, dim, hand, minute }) {
  const ticks = Array.from(
    { length: 12 },
    (_, k) => `
        <path android:name="tick${k}" android:pathData="${tickPath(k)}"
          android:strokeColor="${dim}" android:strokeWidth="3" android:strokeLineCap="round" />`
  ).join('');

  const tickAnims = Array.from(
    { length: LIT_TICKS },
    (_, k) => `
  <target android:name="tick${k}">
    <aapt:attr name="android:animation">
      <set>
        <objectAnimator android:propertyName="strokeColor" android:valueType="colorType"
          android:valueFrom="${dim}" android:valueTo="${lit}"
          android:startOffset="${120 + k * 70}" android:duration="140" />
        <objectAnimator android:propertyName="strokeWidth" android:valueType="floatType"
          android:valueFrom="3" android:valueTo="4.5"
          android:startOffset="${120 + k * 70}" android:duration="140" />
      </set>
    </aapt:attr>
  </target>`
  ).join('');

  const sweep = (name, from, to) => `
  <target android:name="${name}">
    <aapt:attr name="android:animation">
      <objectAnimator android:propertyName="rotation" android:valueType="floatType"
        android:valueFrom="${from}" android:valueTo="${to}" android:duration="${DURATION_MS - 100}"
        android:interpolator="@android:interpolator/fast_out_slow_in" />
    </aapt:attr>
  </target>`;

  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAnimatedSplash.js. Do not edit; change the plugin instead. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
  xmlns:aapt="http://schemas.android.com/aapt">
  <aapt:attr name="android:drawable">
    <vector android:width="108dp" android:height="108dp"
      android:viewportWidth="108" android:viewportHeight="108">
      <group android:name="ticks">${ticks}
      </group>
      <group android:name="minute" android:pivotX="54" android:pivotY="54" android:rotation="180">
        <path android:pathData="M54,54 L54,33" android:strokeColor="${minute}"
          android:strokeWidth="3" android:strokeLineCap="round" />
      </group>
      <group android:name="hour" android:pivotX="54" android:pivotY="54" android:rotation="195">
        <path android:pathData="M54,54 L54,40" android:strokeColor="${hand}"
          android:strokeWidth="5.5" android:strokeLineCap="round" />
      </group>
      <path android:pathData="M54,48.5 a5.5,5.5 0 1,1 0,11 a5.5,5.5 0 1,1 0,-11 z" android:fillColor="${hand}" />
    </vector>
  </aapt:attr>${tickAnims}${sweep('minute', -360, 180)}${sweep('hour', 0, 195)}
</animated-vector>
`;
}

function withAnimatedSplashDrawables(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const res = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res');
      for (const [dir, palette] of [
        ['drawable', palettes.light],
        ['drawable-night', palettes.dark],
      ]) {
        fs.mkdirSync(path.join(res, dir), { recursive: true });
        fs.writeFileSync(path.join(res, dir, `${ICON}.xml`), animatedVector(palette));
      }
      return cfg;
    },
  ]);
}

function withAnimatedSplashTheme(config) {
  return withAndroidStyles(config, (cfg) => {
    const style = cfg.modResults.resources.style?.find((s) => s.$.name === 'Theme.App.SplashScreen');
    if (!style) {
      throw new Error('withAnimatedSplash: Theme.App.SplashScreen not found. Is this plugin listed just before expo-splash-screen?');
    }
    const set = (name, value) => {
      style.item = (style.item ?? []).filter((i) => i.$.name !== name);
      style.item.push({ $: { name }, _: value });
    };
    set('windowSplashScreenAnimatedIcon', `@drawable/${ICON}`);
    set('android:windowSplashScreenAnimationDuration', String(DURATION_MS));
    return cfg;
  });
}

module.exports = function withAnimatedSplash(config) {
  return withAnimatedSplashTheme(withAnimatedSplashDrawables(config));
};
